// cases-size.mjs - hook self-test cases for guard rule 6, the DES-03 read check (CR-2026-10-15-SPLIT).
// Imported by run.mjs, which owns the fixtures and helpers used here. Never run directly.
//
// These replace the three line-count cases of the retired 300/500 rule (a 600-line .py advised, the
// same text in a .md and a 10-line file were silent). The rule they measured no longer exists; each
// behaviour they covered has a case here in bytes, plus the cases the new rule and its review added.

import fs from 'node:fs';
import path from 'node:path';

export default function sizeCases(t) {
    const { brain, repoClean, record, section, jp, put, readText, invokeHook, hookJson, classify } = t;

    section('-- guard rule 6: the DES-03 read check');
    const cfgPath = path.join(brain, 'doctor.config.json');
    const cfgOrig = readText(cfgPath);
    const setCfg = (values) => { const c = JSON.parse(cfgOrig); Object.assign(c, values); put(cfgPath, JSON.stringify(c, null, 2)); };
    const call = (session, tool, ti) => invokeHook('guard.mjs', hookJson({ session_id: session, cwd: repoClean, hook_event_name: 'PreToolUse', tool_name: tool, tool_input: ti }));
    const write = (session, p, content) => call(session, 'Write', { file_path: p, content });
    const edit = (session, p, oldS, newS) => call(session, 'Edit', { file_path: p, old_string: oldS, new_string: newS });
    const got = (r) => (r.code !== 0 ? `exit${r.code}` : classify(r.out));
    const putCrlf = (p, lf) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, lf.replace(/\n/g, '\r\n'), 'utf8'); };
    const big = 'x = 1\n'.repeat(600);     // 3,600 bytes: over the test ceiling of 2,000
    const huge = 'x = 1\n'.repeat(9000);   // 54,000 bytes: over the 49152 default
    const src = path.join(repoClean, 'src');

    setCfg({ readCeilingBytes: 2000, readCeilingExempt: ['**/vendor/**', '**/[slug]/**', 'a/[broken/**'] });
    let r = write('sz-1', path.join(src, 'grow.py'), big);
    record('size: a write that grows a .py past the ceiling -> advises the agent only (no systemMessage)', 'advise-one-channel', got(r), r.out);
    record('size: the note says it is not a request to split', 'said', /not a request to split/i.test(r.out) && /past one Read/i.test(r.out) ? 'said' : 'missing', r.out);
    const logText = readText(process.env.DF_LOG_PATH);
    record('size: each firing is one INFO line in the hooks log', 'logged', /DES-03 read check: .*grow\.py grows to/i.test(logText) ? 'logged' : 'missing');
    record('size: a malformed exempt glob does not throw (no internal error)', 'clean', !/rule 6 \(read check\) skipped/i.test(logText) && !/internal error/i.test(r.out) ? 'clean' : 'threw', r.out);
    r = write('sz-1', path.join(src, 'grow.py'), big);
    record('size: the same file again in the same session -> silent', 'allow', got(r), r.out);
    r = write('sz-2', path.join(repoClean, 'notes.md'), big);
    record('size: the same text into a .md -> silent (not source)', 'allow', got(r), r.out);
    r = write('sz-2', path.join(src, 'small.py'), 'a\nb\n');
    record('size: a small write -> silent', 'allow', got(r), r.out);
    put(path.join(src, 'existing.py'), big);
    r = edit('sz-3', path.join(src, 'existing.py'), 'x = 1\n', '');
    record('size: an edit that shrinks a file over the ceiling -> silent', 'allow', got(r), r.out);
    r = edit('sz-3', path.join(src, 'existing.py'), 'x = 1\n', 'x = 1\ny = 2\n');
    record('size: an edit that grows a file over the ceiling -> advises', 'advise-one-channel', got(r), r.out);
    putCrlf(path.join(src, 'crlf.py'), big);
    r = edit('sz-3', path.join(src, 'crlf.py'), 'x = 1\nx = 1\nx = 1\n', 'x = 1\nx = 1\nx = 1\n' + 'y = 2\n'.repeat(50));
    record('size: a multi-line LF edit that grows a CRLF file -> advises (line endings normalised)', 'advise-one-channel', got(r), r.out);
    putCrlf(path.join(src, 'crlf-write.py'), big);
    r = write('sz-3', path.join(src, 'crlf-write.py'), big + 'y = 2\n'.repeat(50));
    record('size: an LF write that grows a CRLF file -> advises', 'advise-one-channel', got(r), r.out);
    r = edit('sz-3', path.join(src, 'created.py'), '', big);
    record('size: an Edit that creates a file over the ceiling -> advises', 'advise-one-channel', got(r), r.out);
    r = write('sz-4', path.join(src, 'gen.py'), '# GENERATED by build.mjs - do not edit\n' + big);
    record('size: a file whose first lines say generated and do not edit -> silent', 'allow', got(r), r.out);
    r = write('sz-4', path.join(src, 'prose.py'), '# This module was generated by hand from the spec.\n' + big);
    record('size: prose that only mentions generated is not a marker -> advises', 'advise-one-channel', got(r), r.out);
    r = write('sz-4', jp(repoClean, 'vendor', 'lib', 'big.py'), big);
    record('size: a path that matches readCeilingExempt -> silent', 'allow', got(r), r.out);
    r = write('sz-4', jp(repoClean, 'app', '[slug]', 'page.py'), big);
    record('size: an exempt glob with a bracketed folder matches literally -> silent', 'allow', got(r), r.out);

    setCfg({ readCeilingBytes: 0 });
    r = write('sz-5', path.join(src, 'off.py'), huge);
    record('size: readCeilingBytes 0 turns the check off, even past the default', 'allow', got(r), r.out);

    setCfg({ splitLines: 10 });
    r = write('sz-6', path.join(src, 'legacy.py'), big);
    record('size: no readCeilingBytes key -> the 49152 default; an old splitLines key is not read', 'allow', got(r), r.out);
    r = write('sz-6', path.join(src, 'huge.py'), huge);
    record('size: past the 49152 default -> advises', 'advise-one-channel', got(r), r.out);

    put(cfgPath, '{ this is not json');
    r = write('sz-7', path.join(src, 'broken.py'), huge);
    record('size: an unreadable brain config keeps the default read check', 'said', /past one Read/i.test(r.out) ? 'said' : 'off', r.out);

    put(cfgPath, cfgOrig);
}
