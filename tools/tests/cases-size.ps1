# cases-size.ps1 - hook self-test cases for guard rule 6, the DES-03 read check (CR-2026-10-15-SPLIT).
# Dot-sourced by run.ps1. It reads these names from run.ps1's scope: $brain, $repoClean, Put,
# Record, Classify, Invoke-Hook, $env:DF_MARKER_DIR and $env:DF_LOG_PATH. Never run directly.
#
# These replace the three line-count cases of the retired 300/500 rule (a 600-line .py advised, the
# same text in a .md and a 10-line file were silent). The rule they measured no longer exists; each
# behaviour they covered has a case here in bytes, plus the cases the new rule and its review added.

Write-Host '-- guard rule 6: the DES-03 read check'
$sizeCfgPath = Join-Path $brain 'doctor.config.json'
$sizeCfgOrig = Get-Content -LiteralPath $sizeCfgPath -Raw -Encoding utf8
function SetSizeCfg($values) {
    $c = $sizeCfgOrig | ConvertFrom-Json
    foreach ($k in $values.Keys) { $c | Add-Member -NotePropertyName $k -NotePropertyValue $values[$k] -Force }
    Put $sizeCfgPath ($c | ConvertTo-Json -Depth 8)
}
function SizeCall([string]$session, [string]$tool, $ti) {
    $stdin = @{ session_id = $session; cwd = $repoClean; hook_event_name = 'PreToolUse'; tool_name = $tool; tool_input = $ti } | ConvertTo-Json -Compress -Depth 5
    return (Invoke-Hook 'guard.ps1' $stdin)
}
function SizeWrite([string]$session, [string]$path, [string]$content) { return (SizeCall $session 'Write' @{ file_path = $path; content = $content }) }
function SizeEdit([string]$session, [string]$path, [string]$old, [string]$new) { return (SizeCall $session 'Edit' @{ file_path = $path; old_string = $old; new_string = $new }) }
function SizeGot($r) { if ($r.code -ne 0) { return "exit$($r.code)" }; return (Classify $r.out) }
function PutCrlf([string]$path, [string]$lfText) {
    $dir = Split-Path -Parent $path; if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    [IO.File]::WriteAllText($path, $lfText.Replace("`n", "`r`n"), [Text.UTF8Encoding]::new($false))
}
$big  = ('x = 1' + "`n") * 600     # 3,600 bytes: over the test ceiling of 2,000
$huge = ('x = 1' + "`n") * 9000    # 54,000 bytes: over the 49152 default
$src = Join-Path $repoClean 'src'

SetSizeCfg @{ readCeilingBytes = 2000; readCeilingExempt = @('**/vendor/**', '**/[slug]/**', 'a/[broken/**') }
$r = SizeWrite 'sz-1' (Join-Path $src 'grow.py') $big
Record 'size: a write that grows a .py past the ceiling -> advises the agent only (no systemMessage)' 'advise-one-channel' (SizeGot $r) $r.out
Record 'size: the note says it is not a request to split' 'said' $(if ($r.out -match 'not a request to split' -and $r.out -match 'past one Read') { 'said' } else { 'missing' }) $r.out
$logText = if (Test-Path -LiteralPath $env:DF_LOG_PATH) { Get-Content -LiteralPath $env:DF_LOG_PATH -Raw } else { '' }
Record 'size: each firing is one INFO line in the hooks log' 'logged' $(if ($logText -match 'DES-03 read check: .*grow\.py grows to') { 'logged' } else { 'missing' }) ''
Record 'size: a malformed exempt glob does not throw (no internal error)' 'clean' $(if ($logText -notmatch 'rule 6 \(read check\) skipped' -and $r.out -notmatch 'internal error') { 'clean' } else { 'threw' }) $r.out
$r = SizeWrite 'sz-1' (Join-Path $src 'grow.py') $big
Record 'size: the same file again in the same session -> silent' 'allow' (SizeGot $r) $r.out
$r = SizeWrite 'sz-2' (Join-Path $repoClean 'notes.md') $big
Record 'size: the same text into a .md -> silent (not source)' 'allow' (SizeGot $r) $r.out
$r = SizeWrite 'sz-2' (Join-Path $src 'small.py') "a`nb`n"
Record 'size: a small write -> silent' 'allow' (SizeGot $r) $r.out
Put (Join-Path $src 'existing.py') $big
$r = SizeEdit 'sz-3' (Join-Path $src 'existing.py') "x = 1`n" ''
Record 'size: an edit that shrinks a file over the ceiling -> silent' 'allow' (SizeGot $r) $r.out
$r = SizeEdit 'sz-3' (Join-Path $src 'existing.py') "x = 1`n" "x = 1`ny = 2`n"
Record 'size: an edit that grows a file over the ceiling -> advises' 'advise-one-channel' (SizeGot $r) $r.out
PutCrlf (Join-Path $src 'crlf.py') $big
$r = SizeEdit 'sz-3' (Join-Path $src 'crlf.py') "x = 1`nx = 1`nx = 1`n" ("x = 1`nx = 1`nx = 1`n" + ('y = 2' + "`n") * 50)
Record 'size: a multi-line LF edit that grows a CRLF file -> advises (line endings normalised)' 'advise-one-channel' (SizeGot $r) $r.out
PutCrlf (Join-Path $src 'crlf-write.py') $big
$r = SizeWrite 'sz-3' (Join-Path $src 'crlf-write.py') ($big + ('y = 2' + "`n") * 50)
Record 'size: an LF write that grows a CRLF file -> advises' 'advise-one-channel' (SizeGot $r) $r.out
$r = SizeEdit 'sz-3' (Join-Path $src 'created.py') '' $big
Record 'size: an Edit that creates a file over the ceiling -> advises' 'advise-one-channel' (SizeGot $r) $r.out
$r = SizeWrite 'sz-4' (Join-Path $src 'gen.py') ("# GENERATED by build.ps1 - do not edit`n" + $big)
Record 'size: a file whose first lines say generated and do not edit -> silent' 'allow' (SizeGot $r) $r.out
$r = SizeWrite 'sz-4' (Join-Path $src 'prose.py') ("# This module was generated by hand from the spec.`n" + $big)
Record 'size: prose that only mentions generated is not a marker -> advises' 'advise-one-channel' (SizeGot $r) $r.out
$r = SizeWrite 'sz-4' (Join-Path $repoClean 'vendor\lib\big.py') $big
Record 'size: a path that matches readCeilingExempt -> silent' 'allow' (SizeGot $r) $r.out
$r = SizeWrite 'sz-4' (Join-Path $repoClean 'app\[slug]\page.py') $big
Record 'size: an exempt glob with a bracketed folder matches literally -> silent' 'allow' (SizeGot $r) $r.out

SetSizeCfg @{ readCeilingBytes = 0 }
$r = SizeWrite 'sz-5' (Join-Path $src 'off.py') $huge
Record 'size: readCeilingBytes 0 turns the check off, even past the default' 'allow' (SizeGot $r) $r.out

SetSizeCfg @{ splitLines = 10 }
$r = SizeWrite 'sz-6' (Join-Path $src 'legacy.py') $big
Record 'size: no readCeilingBytes key -> the 49152 default; an old splitLines key is not read' 'allow' (SizeGot $r) $r.out
$r = SizeWrite 'sz-6' (Join-Path $src 'huge.py') $huge
Record 'size: past the 49152 default -> advises' 'advise-one-channel' (SizeGot $r) $r.out

Put $sizeCfgPath '{ this is not json'
$r = SizeWrite 'sz-7' (Join-Path $src 'broken.py') $huge
Record 'size: an unreadable brain config keeps the default read check' 'said' $(if ($r.out -match 'past one Read') { 'said' } else { 'off' }) $r.out

Put $sizeCfgPath $sizeCfgOrig
