// remove.mjs - reverses what adopt.mjs wrote, and nothing else. Called by commands/remove.md.
//
//   node tools/remove.mjs [-DryRun]
//
// Reads the pointer, then <brain>/state/installed.json (SPEC 5.6, findings 58, 77):
//   - a recorded file whose sha256 (over CRLF->LF bytes) still matches  -> deleted (kit-authored, unedited)
//   - a recorded file with generated: true                            -> deleted regardless (regenerable)
//   - a recorded file whose hash no longer matches                    -> KEPT and listed (the owner edited it)
//   - a file that is not in the record                                -> never looked at
// The vendored kit (0.3.0, KIT-01): the record's vendored rows, { path: '.claude/kit/<rel>', sha256 }
// as tools/vendor.mjs -Record writes them, relative to the folder adopt vendored into, are resolved
// against the pointer's root and its brain (the two folders adopt vendors, with the same kit's bytes
// in both). A copy whose sha still matches is deleted; an edited copy is KEPT and listed; the copy's
// VERSION goes with it (generated by vendor.mjs, it would name bytes that are gone) and the kit
// folders left empty are removed. A line is not a file: when the brain .gitignore adopt wrote was
// edited, it is kept, and the summary says the state/ lines adopt wrote in it stay.
// Then deletes the pointer, the once-per-session markers (<os temp>/design-first) and <brain>/state,
// and prints the `claude plugin uninstall` line. It never touches the user-level settings.json, and
// never a repository's own .claude/settings.json that adopt merged the hooks block into (not recorded).
// -DryRun prints every decision and deletes nothing.
// Test seams: DF_POINTER_PATH, DF_MARKER_DIR.

import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from './lib/args.mjs';
import * as F from './lib/df-files.mjs';
import { pathEq } from '../hooks/lib/common.mjs';

const say = (s = '') => process.stdout.write(s + '\n');
const isFile = (p) => { try { return fs.statSync(p).isFile(); } catch { return false; } };
const isDir = (p) => { try { return fs.statSync(p).isDirectory(); } catch { return false; } };

// Bottom-up: a folder whose children are all empty folders goes too, and dir itself when empty.
function pruneEmptyFolders(dir) {
    if (!isDir(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) if (e.isDirectory()) pruneEmptyFolders(path.join(dir, e.name));
    if (fs.readdirSync(dir).length > 0) return;
    fs.rmdirSync(dir);
    say(`  removed   ${dir}  (empty folder)`);
}

try {
    const opts = parseArgs(process.argv.slice(2), { switches: ['DryRun'] });
    const dryRun = opts.DryRun;
    const verb = dryRun ? 'would delete' : 'deleted';
    const rm = (p) => { if (!dryRun) fs.rmSync(p, { recursive: true, force: true }); };
    const pointerPath = F.pointerFile();
    const markerDir = F.markerFolder();
    say();
    say(`design-first remove${dryRun ? '  [DRY RUN: nothing is deleted]' : ''}`);
    say(`  pointer   ${pointerPath}`);

    let brain = null; let root = null;
    if (fs.existsSync(pointerPath)) {
        try {
            const p = F.readJson(pointerPath);
            if (p.brain) brain = F.fullPath(String(p.brain));
            if (p.root) root = F.fullPath(String(p.root));
        } catch (e) { say(`  WARNING   pointer could not be parsed (${e.message}); no record to read`); }
    } else say('  (no pointer: nothing was adopted on this profile, or it was removed already)');

    let deleted = 0; let gone = 0; const keptList = []; const deletedList = [];
    let vendoredRows = 0; let vendoredDeleted = 0; let vendoredGone = 0; let vendoredKept = 0;
    if (brain) {
        say(`  brain     ${brain}`);
        const installedPath = path.join(brain, 'state', 'installed.json');
        if (!fs.existsSync(installedPath)) say(`  (no ${installedPath}: nothing recorded, so no file is deleted)`);
        else {
            say();
            say('recorded files');
            for (const rec of F.readInstalled(installedPath)) {
                const p = rec.path;
                if (!isFile(p)) { say(`  gone      ${p}`); gone++; continue; }
                if (rec.generated) { say(`  ${verb}   ${p}  (generated: regenerable)`); rm(p); deleted++; deletedList.push(p); continue; }
                if (F.fileSha256(p) === rec.sha256) { say(`  ${verb}   ${p}  (unchanged since adopt)`); rm(p); deleted++; deletedList.push(p); continue; }
                say(`  KEPT      ${p}  (edited since adopt; yours)`);
                keptList.push(p);
            }
            // Folders adopt created that are now empty. Only these two; anything else is not ours to judge.
            for (const d of ['entry-point', 'instructions']) {
                const dir = path.join(brain, d);
                if (isDir(dir) && !dryRun && fs.readdirSync(dir).length === 0) {
                    fs.rmdirSync(dir); say(`  removed   ${dir}  (empty folder)`);
                }
            }

            // The vendored kit (0.3.0): one row per copied file, relative to the folder it was copied
            // into; the root and the brain both get a copy, so a row is read against both.
            const vendored = F.readVendored(installedPath);
            vendoredRows = vendored.length;
            if (vendored.length > 0) {
                say();
                say('vendored kit (recorded by tools/vendor.mjs; a copy is deleted only when its sha still matches)');
                const bases = [];
                for (const b of [root, brain]) if (b && !bases.some((x) => pathEq(x, b))) bases.push(b);
                const touched = [];
                for (const row of vendored) {
                    let seen = 0;
                    for (const base of bases) {
                        const full = path.isAbsolute(row.path) ? row.path : path.join(base, row.path);
                        if (!isFile(full)) { if (path.isAbsolute(row.path)) break; continue; }
                        seen++;
                        if (!touched.some((x) => pathEq(x, base))) touched.push(base);
                        if (F.fileSha256(full) === row.sha256) { say(`  ${verb}   ${full}  (vendored, unchanged since adopt)`); rm(full); vendoredDeleted++; }
                        else { say(`  KEPT      ${full}  (vendored, edited since adopt; yours)`); keptList.push(full); vendoredKept++; }
                        if (path.isAbsolute(row.path)) break;
                    }
                    if (seen === 0) { say(`  gone      ${row.path}  (vendored; in no copy)`); vendoredGone++; }
                }
                for (const base of touched) {
                    const kitDir = path.join(base, '.claude', 'kit');
                    const versionFile = path.join(kitDir, 'VERSION');
                    if (isFile(versionFile)) { say(`  ${verb}   ${versionFile}  (generated by tools/vendor.mjs; it named bytes that are gone)`); rm(versionFile); }
                    if (!dryRun) pruneEmptyFolders(kitDir);
                }
            }
        }
        const stateDir = path.join(brain, 'state');
        if (fs.existsSync(stateDir)) { say(`  ${verb}   ${stateDir}${path.sep}  (generated state)`); rm(stateDir); }
    }

    if (fs.existsSync(markerDir)) { say(`  ${verb}   ${markerDir}${path.sep}  (session markers)`); rm(markerDir); }
    if (fs.existsSync(pointerPath)) { say(`  ${verb}   ${pointerPath}  (pointer)`); rm(pointerPath); }

    say();
    say('summary');
    say(`  deleted   ${deleted} recorded file(s); ${gone} already gone`);
    if (vendoredRows > 0) say(`  vendored  ${vendoredDeleted} copied file(s) deleted; ${vendoredKept} kept (edited); ${vendoredGone} already gone`);
    if (keptList.length > 0) {
        say(`  kept      ${keptList.length} file(s) you edited since adopt - delete them yourself if you want them gone:`);
        for (const k of keptList) say(`              ${k}`);
    } else say('  kept      nothing: no recorded file had been edited');
    if (brain) {
        const gi = path.join(brain, '.gitignore');
        if (keptList.some((k) => pathEq(k, gi))) say(`  .gitignore  ${gi} is kept (you edited it): the state/ lines adopt wrote in it stay, a line is not a file; delete them yourself if you want them gone`);
        else if (deletedList.some((k) => pathEq(k, gi))) say(`  .gitignore  ${verb} ${gi} (unchanged since adopt): its state/ lines went with the file`);
    }
    say('  untouched user-level settings.json (this script never writes or deletes it; remove any soft_deny lines you pasted by hand)');
    say();
    say('  Finish with:');
    say('    claude plugin uninstall design-first');
    say();
    process.exitCode = 0;
} catch (e) {
    say();
    say(`remove: ERROR ${e.message}`);
    process.exitCode = 1;
}
